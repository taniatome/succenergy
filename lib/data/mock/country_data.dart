  /// Countries sorted for [localeCode].
  static List<Country> sortedFor(String localeCode) {
    final List<Country> sorted = List<Country>.from(all);
    sorted.sort(
      (Country a, Country b) =>
          a.nameFor(localeCode).compareTo(b.nameFor(localeCode)),
    );
    return sorted;
  }

  /// The country matching [code], or null when nothing is stored yet.
  static Country? byCode(String? code) {
    if (code == null) {
      return null;
    }
    for (final Country country in all) {
      if (country.code == code) {
        return country;
      }
    }
    return null;
  }

